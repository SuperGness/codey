// Open remote-workspace-browser.html with Playwright CLI, then run-code --filename this file.
async page => {
  if (!page.url().endsWith('/codey/tests/remote-workspace-browser.html')) throw new Error('Open the mock workspace fixture first');
  await page.evaluate(() => sessionStorage.clear());
  await page.reload();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ colorScheme: 'dark' });
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const ready = async () => {
    // Let React finish the settings response and reconnect effect before checking the new socket.
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await page.waitForFunction(() => { const select = document.querySelector('select[aria-label="模型"]'); return select && !select.disabled; });
  };
  const advanced = async () => {
    await page.getByRole('button', { name: '调整模型与思考强度' }).click();
    await page.getByRole('button', { name: /^高级设置：/ }).click();
    await page.getByRole('dialog', { name: '高级设置' }).waitFor();
  };
  const chooseSettings = async (name, value) => {
    await advanced();
    await page.getByLabel(name, { exact: true }).selectOption(value); await ready();
    await page.getByRole('button', { name: '关闭高级设置' }).click();
  };
  const openFirst = async () => { await page.getByRole('button', { name: /重新设计界面/ }).click(); await ready(); };
  const layout = async () => {
    await page.waitForFunction(() => Math.abs(document.querySelector('.remote-shell').getBoundingClientRect().height - (window.visualViewport?.height || innerHeight)) < 1);
    const result = await page.evaluate(() => ({
      composer: document.querySelector('.remote-composer').getBoundingClientRect().toJSON(),
      width: innerWidth, height: innerHeight, documentWidth: document.documentElement.scrollWidth,
    }));
    assert(result.composer.bottom <= result.height + 1 && result.composer.top >= 0, `Composer outside viewport: ${JSON.stringify(result)}`);
    assert(result.composer.right <= result.width && result.documentWidth <= result.width, 'Horizontal page overflow');
  };
  await page.getByRole('button', { name: /重新设计界面/ }).waitFor();
  assert(await page.locator('.remote-project').first().locator('.remote-thread').count() === 5, 'Windows extended paths did not group under their project');
  await page.getByRole('button', { name: 'codey', exact: true }).click();
  assert(await page.locator('.remote-project').first().locator('.remote-thread').count() === 0, 'Project did not collapse');
  await page.getByRole('button', { name: 'codey', exact: true }).click();
  await page.getByRole('button', { name: '展开显示 (2)', exact: true }).click();
  assert(await page.locator('.remote-project').first().locator('.remote-thread').count() === 7, 'Expanded project is missing conversations');
  await page.screenshot({ path: 'output/playwright/remote-mobile-projects.png' });
  await openFirst();
  await layout();
  assert(await page.locator('.remote-markdown table').count() === 1, 'Markdown table missing');
  assert(await page.locator('.hljs-keyword').count() > 0, 'Code highlighting missing');
  assert(await page.locator('.remote-work-log[open]').count() === 0, 'Work log should start folded');
  await page.screenshot({ path: 'output/playwright/remote-mobile-chat-dark.png' });
  assert(await page.getByRole('img', { name: '快速模式已启用' }).count() === 0, 'Standard mode displays lightning');
  const beforeSlider = await page.evaluate(() => window.remoteFixture.actions.length);
  await page.getByRole('button', { name: '调整模型与思考强度' }).click();
  const slider = page.getByRole('slider', { name: '思考强度' });
  assert(await slider.getAttribute('aria-valuetext') === '高', 'Slider did not show the current effort');
  const bounds = await slider.boundingBox();
  await page.mouse.move(bounds.x + 22, bounds.y + bounds.height / 2); await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width - 22, bounds.y + bounds.height / 2, { steps: 8 });
  assert(await slider.getAttribute('aria-valuetext') === 'Ultra', 'Dragging did not preview the effort');
  assert(await page.evaluate(() => window.remoteFixture.actions.length) === beforeSlider, 'Dragging sent settings before release');
  await page.mouse.up(); await ready();
  assert(await page.getByLabel('思考程度', { exact: true }).inputValue() === 'ultra', 'Slider did not commit on release');
  assert(await page.evaluate(() => window.remoteFixture.actions.length) === beforeSlider + 1, 'Slider submitted more than once');
  await slider.focus(); await page.keyboard.press('Home'); await ready();
  assert(await page.getByLabel('思考程度', { exact: true }).inputValue() === 'low', 'Keyboard cannot adjust the slider');
  await page.keyboard.press('Escape');
  assert(await page.getByRole('button', { name: '调整模型与思考强度' }).evaluate(element => element === document.activeElement), 'Popover did not restore focus');
  const beforeAttachments = await page.evaluate(() => window.remoteFixture.actions.length);
  for (const name of ['相机', '照片']) {
    await page.getByRole('button', { name: '添加附件', exact: true }).click();
    await page.getByRole('button', { name, exact: true }).click();
    await page.getByText(`${name}功能暂未开放`, { exact: true }).waitFor();
  }
  assert(await page.evaluate(() => window.remoteFixture.actions.length) === beforeAttachments, 'Attachment placeholders sent an action');
  assert(await page.locator('input[type="file"]').count() === 0, 'Placeholder requested local files');
  await advanced(); await page.keyboard.press('Escape');
  assert(await page.getByRole('dialog').count() === 0, 'Escape did not close the advanced sheet');
  assert(await page.getByRole('button', { name: '调整模型与思考强度' }).evaluate(element => element === document.activeElement), 'Sheet did not restore focus');
  await chooseSettings('思考程度', 'ultra'); await ready();
  assert(await page.getByLabel('思考程度', { exact: true }).inputValue() === 'ultra', 'Effort did not synchronize');
  await chooseSettings('模型', 'route-demo/gpt-6-sol'); await ready();
  assert(await page.getByLabel('思考程度', { exact: true }).inputValue() === 'low', 'Unsupported effort not replaced with model default');
  assert(await page.getByLabel('思考程度', { exact: true }).locator('option').count() === 2, 'Unsupported effort shown');
  await page.getByLabel('权限', { exact: true }).selectOption('full-access'); await ready();
  assert(await page.getByLabel('权限', { exact: true }).inputValue() === 'full-access', 'Permission did not synchronize');
  await chooseSettings('速度模式', 'priority'); await ready();
  assert(await page.getByLabel('速度模式', { exact: true }).inputValue() === 'priority', 'Fast did not synchronize');
  assert(await page.getByRole('img', { name: '快速模式已启用' }).count() === 1, 'Fast did not display lightning');
  await chooseSettings('速度模式', 'default'); await ready();
  assert(await page.getByLabel('速度模式', { exact: true }).inputValue() === 'default', 'Fast could not be disabled');
  assert(await page.getByRole('img', { name: '快速模式已启用' }).count() === 0, 'Disabled Fast retained lightning');
  const input = page.getByLabel('发送给 Codex 的指令');
  await input.fill('保留这份草稿');
  await page.getByRole('button', { name: '返回会话列表' }).click();
  await page.getByRole('button', { name: /添加手机远程控制功能/ }).click(); await ready();
  assert(await input.inputValue() === '', 'Draft leaked into another thread');
  await page.getByRole('button', { name: '返回会话列表' }).click();
  await openFirst();
  assert(await input.inputValue() === '保留这份草稿', 'Thread draft lost');
  const beforeDisconnect = await page.evaluate(() => window.remoteFixture.actions.length);
  await page.evaluate(() => window.remoteFixture.disconnect());
  assert(await page.getByRole('button', { name: '发送消息', exact: true }).isDisabled(), 'Sending allowed while disconnected');
  await ready();
  assert(await input.inputValue() === '保留这份草稿', 'Reconnect lost draft');
  assert(await page.getByLabel('速度模式', { exact: true }).inputValue() === 'default', 'Reconnect reset the selected speed');
  assert(await page.evaluate(() => window.remoteFixture.actions.length) === beforeDisconnect, 'Reconnect replayed an action');
  const connections = await page.evaluate(() => { window.remoteFixture.unavailable(); return window.remoteFixture.connections; });
  await page.getByText('桌面暂时无法读取此会话', { exact: true }).waitFor();
  await page.waitForTimeout(2300);
  assert(await page.evaluate(() => window.remoteFixture.connections) === connections, 'Desktop failure retried automatically');
  await page.getByRole('button', { name: '重新连接' }).click(); await ready();
  assert(await page.evaluate(() => window.remoteFixture.actions.some(a => a.action === 'open')) === false, 'Opening or reconnecting launched an extra action');
  await page.evaluate(() => window.remoteFixture.failNext = true);
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await page.getByText('消息未确认。请查看会话是否已收到，确认后再决定是否重新发送。').waitFor();
  assert(await input.inputValue() === '保留这份草稿', 'Uncertain submission lost draft');
  assert(await page.getByRole('button', { name: '发送消息', exact: true }).isDisabled(), 'Uncertain submission allowed duplicate send');
  await page.getByRole('button', { name: '已核对，允许再次发送' }).click();
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await page.getByRole('button', { name: '停止任务' }).waitFor();
  assert(await input.inputValue() === '', 'Successful send did not clear draft');
  await input.fill('再补充一条指令');
  await page.getByRole('button', { name: '补充指令', exact: true }).click();
  await page.getByRole('button', { name: '停止任务' }).click();
  await page.getByText('已停止', { exact: true }).waitFor();
  const actions = await page.evaluate(() => window.remoteFixture.actions);
  assert(actions.some(a => a.action === 'steer') && actions.some(a => a.action === 'interrupt'), 'Steer or stop missing');
  assert(new Set(actions.map(a => a.requestId)).size === actions.length, 'Request IDs reused');
  await page.getByRole('button', { name: '返回会话列表' }).click();
  await page.getByRole('button', { name: '在 codex-proxy-plugin 中新建会话' }).click();
  await ready();
  assert(await page.getByLabel('项目', { exact: true }).inputValue() === 'proxy', 'Project creation context lost');
  assert(await page.getByRole('dialog').count() === 0 && await page.getByLabel('会话名称').count() === 0, 'New conversation still requires a title dialog');
  await page.getByRole('heading', { name: '从一个想法开始' }).waitFor();
  assert(await input.inputValue() === '', 'New conversation did not start with a blank draft');
  assert(await page.getByLabel('模型', { exact: true }).inputValue() === 'route-demo/gpt-6-astra', 'Desktop default model was not selected');
  assert(await page.getByLabel('思考程度', { exact: true }).inputValue() === 'ultra', 'Desktop default effort was not selected');
  assert(await page.getByLabel('速度模式', { exact: true }).inputValue() === 'priority', 'Desktop default speed was not selected');
  await input.fill('手机端新建验证');
  await chooseSettings('模型', 'route-demo/gpt-6-sol');
  await page.getByLabel('权限', { exact: true }).selectOption('read-only');
  await chooseSettings('速度模式', 'default');
  await page.getByLabel('项目', { exact: true }).selectOption('codey');
  assert(await input.inputValue() === '', 'Draft leaked into another project');
  await page.getByLabel('项目', { exact: true }).selectOption('proxy');
  await ready();
  assert(await input.inputValue() === '手机端新建验证' && await page.getByLabel('模型', { exact: true }).inputValue() === 'route-demo/gpt-6-sol', 'Project draft or settings lost');
  assert(await page.getByLabel('速度模式', { exact: true }).inputValue() === 'default', 'Project draft lost its explicit standard speed');
  assert(await page.evaluate(() => window.remoteFixture.creations.length) === 0, 'An untouched draft created a persisted conversation');
  await layout(); await page.screenshot({ path: 'output/playwright/remote-mobile-draft.png' });
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await page.getByRole('heading', { name: '手机端新建验证', exact: true }).waitFor(); await ready();
  await page.getByRole('button', { name: '停止任务' }).waitFor();
  const creation = await page.evaluate(() => window.remoteFixture.creations);
  assert(creation.length === 1 && creation[0].text === '手机端新建验证' && creation[0].projectId === 'proxy' && !('title' in creation[0]), 'First message did not drive native creation');
  assert(creation[0].model === 'route-demo/gpt-6-sol' && creation[0].permissionMode === 'read-only', 'Draft settings lost during creation');
  assert(creation[0].effort === 'low' && creation[0].serviceTier === 'default', 'First turn lost reasoning or speed settings');
  assert(await input.inputValue() === '', 'Accepted first message remained in the composer');
  await page.getByRole('button', { name: '新建会话', exact: true }).click();
  await ready();
  await input.fill('未确认的新会话');
  await page.evaluate(() => window.remoteFixture.failCreate = true);
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await page.getByRole('button', { name: '已核对，允许再次发送' }).waitFor();
  assert(await page.getByRole('button', { name: '发送消息', exact: true }).isDisabled(), 'Uncertain creation can be duplicated');
  await page.evaluate(() => { window.remoteFixture.defaults = { model: 'route-demo/gpt-6-sol', effort: 'low', serviceTier: 'default' }; });
  await page.getByRole('button', { name: '返回会话列表' }).click();
  await page.getByRole('button', { name: '在 codex-proxy-plugin 中新建会话' }).click(); await ready();
  assert(await page.getByLabel('模型', { exact: true }).inputValue() === 'route-demo/gpt-6-astra' && await page.getByLabel('思考程度', { exact: true }).inputValue() === 'ultra' && await page.getByLabel('速度模式', { exact: true }).inputValue() === 'priority', 'New desktop defaults changed an unconfirmed submission');
  await page.reload();
  await page.getByRole('button', { name: '在 codex-proxy-plugin 中新建会话' }).click(); await ready();
  assert(await input.inputValue() === '未确认的新会话', 'Reload lost unconfirmed creation text');
  assert(await page.getByLabel('速度模式', { exact: true }).inputValue() === 'priority', 'Reload lost unconfirmed speed settings');
  assert(await page.getByRole('button', { name: '发送消息', exact: true }).isDisabled(), 'Reload allowed unconfirmed creation to replay');
  assert(await page.evaluate(() => window.remoteFixture.creations.length) === 0, 'Reload replayed creation');
  await page.getByRole('button', { name: '已核对，允许再次发送' }).click();
  await page.evaluate(() => window.remoteFixture.firstTurn = 'not-started');
  await page.getByRole('button', { name: '发送消息', exact: true }).click(); await ready();
  await page.getByRole('heading', { name: '未确认的新会话', exact: true }).waitFor();
  assert(await input.inputValue() === '未确认的新会话', 'Unsent first message was discarded');
  assert(await page.evaluate(() => window.remoteFixture.actions.length) === 0, 'Unsent first message was retried automatically');
  await page.getByRole('button', { name: '新建会话', exact: true }).click();
  await ready();
  await input.fill('第一条消息结果不明');
  await page.evaluate(() => window.remoteFixture.firstTurn = 'outcome-unknown');
  await page.getByRole('button', { name: '发送消息', exact: true }).click(); await ready();
  await page.getByRole('heading', { name: '第一条消息结果不明', exact: true }).waitFor();
  assert(await input.inputValue() === '第一条消息结果不明', 'Unconfirmed first message was discarded');
  assert(await page.getByRole('button', { name: '补充指令', exact: true }).isDisabled(), 'Unconfirmed first message can be replayed');
  await page.getByRole('button', { name: '返回会话列表' }).click();
  await page.evaluate(() => { window.remoteFixture.defaultsFail = true; });
  await page.getByRole('button', { name: '在 FreeRTOS-LTS 中新建会话' }).click();
  await input.fill('等待默认设置');
  await page.getByText('桌面默认设置暂时无法加载，请重试。', { exact: false }).waitFor();
  assert(await page.getByRole('button', { name: '发送消息', exact: true }).isDisabled(), 'A failed defaults read allowed submission');
  await page.evaluate(() => { window.remoteFixture.defaultsFail = false; });
  await page.getByRole('button', { name: '重试', exact: true }).click(); await ready();
  assert(await input.inputValue() === '等待默认设置', 'Retry lost the draft');
  await page.evaluate(() => { window.remoteFixture.defaultsDelay = 400; });
  await page.getByLabel('项目', { exact: true }).selectOption('codey');
  await page.waitForTimeout(50);
  await page.getByRole('button', { name: '返回会话列表' }).click();
  await openFirst();
  await page.waitForTimeout(450);
  assert(await page.getByLabel('速度模式', { exact: true }).inputValue() === 'default', 'A late defaults response overwrote the selected conversation');
  await page.getByRole('button', { name: '返回会话列表' }).click();
  await openFirst();
  await page.emulateMedia({ colorScheme: 'light' });
  await page.screenshot({ path: 'output/playwright/remote-mobile-chat-light.png' });
  await page.setViewportSize({ width: 320, height: 568 }); await layout();
  await page.screenshot({ path: 'output/playwright/remote-mobile-narrow.png' });
  await page.setViewportSize({ width: 390, height: 450 });
  await input.fill('模拟键盘弹出后继续输入'); await input.focus(); await layout();
  await page.screenshot({ path: 'output/playwright/remote-mobile-keyboard.png' });
  await page.setViewportSize({ width: 1440, height: 900 }); await layout();
  await page.getByRole('button', { name: /重新设计界面/ }).click();
  assert(await page.locator('.remote-markdown table').count() === 1, 'Selecting the current conversation cleared its view');
  await input.fill('');
  await page.locator('.remote-messages').evaluate(element => element.scrollTop = 0);
  await page.screenshot({ path: 'output/playwright/remote-desktop-chat.png' });
  await page.getByRole('button', { name: '搜索会话' }).click();
  await page.getByRole('searchbox').fill('远程控制验收');
  await page.getByRole('button', { name: /远程控制验收/ }).waitFor();
  await page.waitForFunction(() => document.querySelectorAll('.remote-thread').length === 1);
  await page.getByRole('searchbox').fill('');
  await page.getByRole('button', { name: /重新设计界面/ }).waitFor();
  await page.getByRole('button', { name: 'Codey 控制台' }).click();
  await page.getByRole('button', { name: '返回 Codex' }).click();
  await ready(); await layout();
  await page.evaluate(() => { window.remoteFixture.unauthorized = true; window.remoteFixture.unavailable(); });
  await page.getByRole('heading', { name: '连接你的 Codey' }).waitFor();
  return { passed: ['Windows project grouping', 'Markdown and code', 'Settings synchronization', 'Fast on and off', 'Desktop draft defaults', 'Defaults retry and stale responses', 'Supported efforts', 'Per-thread drafts', 'Reconnect without replay', 'Desktop failure stops automatic retries', 'Uncertain send protection', 'Send, steer and stop', 'Blank project drafts', 'Native creation on first send', 'Uncertain creation survives reload', 'Unsent first message preserved', 'Uncertain first message protected', '320px and keyboard viewport', 'Dark and light themes', 'Search and console navigation', 'Revoked device returns to pairing'], actionCount: actions.length };
}
